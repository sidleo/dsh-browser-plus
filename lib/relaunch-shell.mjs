/**
 * 生成「自动带调试端口重启 DSH」的 zsh 脚本（纯函数，便于单测）。
 *
 * 约束与依据（macOS 本机实测）：
 * - 调试端口只能在 Electron 进程启动瞬间打开，所以自动桥接必须让应用重启一次；
 * - 直接执行应用二进制并带 `--remote-debugging-port` 最可靠（`open --args` 在应用未完全退出时会被忽略）；
 * - 必须等主进程与 Host 子进程都真正退出、且 Chromium 单例锁释放后再启动，否则新实例会秒退；
 * - 启动后必须验证端口；失败重试有上限；
 * - 最终失败要回退为「正常启动 DSH」，绝不能让用户没有应用可用。
 *
 * 脚本运行结果写到 resultFile（JSON：outcome/at/port/detail），供下次启动判断是否重试。
 */

/** 最多尝试启动次数。 */
export const RELAUNCH_MAX_ATTEMPTS = 3

/**
 * @param {{
 *   appBundle: string,
 *   executableName: string,
 *   port: number,
 *   logFile: string,
 *   resultFile: string,
 * }} input
 * @returns {string} zsh 脚本正文
 */
export function buildRelaunchScript({ appBundle, executableName, port, logFile, resultFile }) {
  const appBin = `${appBundle}/Contents/MacOS/${executableName}`
  const quitCommand = `quit app "${executableName}"`
  const lines = [
    '#!/bin/zsh',
    '# dsh-browser-plus 自动桥接：以带本机 DevTools 调试端口的方式重启 DSH。',
    '# 端口只监听 127.0.0.1；若最终失败，回退为正常启动 DSH，保证应用可用。',
    `APP_BUNDLE=${JSON.stringify(appBundle)}`,
    `APP_BIN=${JSON.stringify(appBin)}`,
    `PORT="${port}"`,
    `LOG=${JSON.stringify(logFile)}`,
    `RESULT=${JSON.stringify(resultFile)}`,
    `MAX_ATTEMPTS=${RELAUNCH_MAX_ATTEMPTS}`,
    'mkdir -p "$(dirname "$LOG")" "$(dirname "$RESULT")" 2>/dev/null',
    'exec >>"$LOG" 2>&1',
    'stamp() { date \'+%F %T\'; }',
    'echo "==================== $(stamp) auto bridge (port $PORT) ===================="',
    'bridge_up() { curl -s --max-time 2 "http://127.0.0.1:$PORT/json/version" >/dev/null 2>&1; }',
    'write_result() { printf \'{"outcome":"%s","at":%s,"port":%s,"detail":"%s"}\\n\' "$1" "$(date +%s)" "$PORT" "${2:-}" > "$RESULT" 2>/dev/null || true; }',
    'port_in_use() { lsof -nP -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1; }',
    '# 只认主进程：命令行以 APP_BIN 开头、且不带 expose-internals（Host 子进程用同一二进制冒充）。',
    'main_pids() {',
    '  ps -ax -o pid=,command= 2>/dev/null | while read -r pid cmd; do',
    '    case "$cmd" in',
    '      "$APP_BIN"*)',
    '        case "$cmd" in *expose-internals*) continue;; esac',
    '        echo "$pid"',
    '        ;;',
    '    esac',
    '  done',
    '}',
    'host_pids() {',
    '  ps -ax -o pid=,command= 2>/dev/null | while read -r pid cmd; do',
    '    case "$cmd" in',
    '      "$APP_BIN"*)',
    '        case "$cmd" in *expose-internals*) echo "$pid";; esac',
    '        ;;',
    '    esac',
    '  done',
    '}',
    'wait_gone() { # $1 进程集合函数名，$2 轮数（每轮 0.5s）',
    '  local fn="$1" cycles="$2" i=0',
    '  while [ "$i" -lt "$cycles" ]; do',
    '    [ -z "$($fn)" ] && return 0',
    '    sleep 0.5',
    '    i=$((i + 1))',
    '  done',
    '  [ -z "$($fn)" ]',
    '}',
    'kill_set() { # $1 进程集合函数名，$2 信号',
    '  local fn="$1" sig="$2" pid',
    '  for pid in $($fn); do kill -"$sig" "$pid" 2>/dev/null; done',
    '}',
    'quit_dsh() {',
    '  osascript -e ' + JSON.stringify(quitCommand) + ' 2>/dev/null',
    '  wait_gone main_pids 40 || kill_set main_pids TERM',
    '  wait_gone main_pids 10 || kill_set main_pids KILL',
    '  # Host 子进程也要退出：否则新实例启动时 profile 锁未释放',
    '  wait_gone host_pids 20 || kill_set host_pids TERM',
    '  wait_gone host_pids 10 || kill_set host_pids KILL',
    '  [ -z "$(main_pids)" ] && [ -z "$(host_pids)" ]',
    '}',
    'wait_port_free() {',
    '  local i=0',
    '  while [ "$i" -lt 20 ]; do',
    '    port_in_use || return 0',
    '    sleep 0.5',
    '    i=$((i + 1))',
    '  done',
    '  ! port_in_use',
    '}',
    'launch_once() {',
    '  echo "[$(stamp)] launch: $APP_BIN --remote-debugging-port=$PORT"',
    '  nohup env -u ELECTRON_RUN_AS_NODE -u NODE_OPTIONS "$APP_BIN" --remote-debugging-port="$PORT" >>"$LOG" 2>&1 &',
    '  local lpid=$! i=0',
    '  while [ "$i" -lt 60 ]; do',
    '    if bridge_up; then return 0; fi',
    '    kill -0 "$lpid" 2>/dev/null || return 2',
    '    sleep 0.5',
    '    i=$((i + 1))',
    '  done',
    '  return 1',
    '}',
    'echo "[$(stamp)] quit DSH"',
    'if ! quit_dsh; then',
    '  echo "[$(stamp)] WARN: DSH 未能完全退出，跳过本次自动重启（避免双实例），保持现状"',
    '  write_result failed quit-blocked',
    '  exit 1',
    'fi',
    'wait_port_free || echo "[$(stamp)] WARN: port $PORT 仍被占用，继续尝试"',
    'sleep 2',
    'attempt=1',
    'while [ "$attempt" -le "$MAX_ATTEMPTS" ]; do',
    '  echo "[$(stamp)] attempt $attempt/$MAX_ATTEMPTS"',
    '  launch_once',
    '  rc=$?',
    '  if [ "$rc" -eq 0 ]; then',
    '    echo "[$(stamp)] OK: bridge up on port $PORT"',
    '    write_result ok "launched-${attempt}"',
    '    exit 0',
    '  fi',
    '  echo "[$(stamp)] attempt $attempt failed (code $rc)"',
    '  if [ "$rc" -ne 2 ]; then',
    '    # 进程还活着但端口没起来：先清理再重试',
    '    kill_set main_pids TERM',
    '    kill_set host_pids TERM',
    '    sleep 1',
    '    kill_set main_pids KILL',
    '    sleep 1',
    '  fi',
    '  wait_port_free || true',
    '  sleep 2',
    '  attempt=$((attempt + 1))',
    'done',
    'echo "[$(stamp)] FAILED: 未能带端口启动，回退为正常启动 DSH（保证应用可用）"',
    'if [ -n "$(main_pids)" ] || [ -n "$(host_pids)" ]; then',
    '  kill_set main_pids TERM',
    '  kill_set host_pids TERM',
    '  sleep 2',
    '  kill_set main_pids KILL',
    '  sleep 1',
    'fi',
    'open -a "$APP_BUNDLE" 2>/dev/null || nohup env -u ELECTRON_RUN_AS_NODE -u NODE_OPTIONS "$APP_BIN" >>"$LOG" 2>&1 &',
    'write_result failed port-not-ready',
    'exit 1',
  ]
  return lines.join('\n') + '\n'
}
